// Writes docs/spec/coverage/: which APRS101 test vectors (tests/AprsNet.Packets.SpecTests/Vectors) have also been seen in
// real traffic (tests/corpus). A vector counts as seen when one corpus packet matches all of the vector's features.
//
//   dotnet run tools/corpus/Coverage.cs            (from the repository root)

using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

const string vectorsDir = "tests/AprsNet.Packets.SpecTests/Vectors";
const string corpusDir = "tests/corpus";
const string outDir = "docs/spec/coverage";
var latin1 = Encoding.Latin1;
var inv = CultureInfo.InvariantCulture;

if (!Directory.Exists(vectorsDir) || !Directory.Exists(corpusDir))
{
    Console.Error.WriteLine("Run from the repository root.");
    return 3;
}

var features = JsonDocument
    .Parse(File.ReadAllText(Path.Combine(vectorsDir, "features.json")))
    .RootElement.GetProperty("features")
    .EnumerateArray()
    .Select(f => new Feature(
        f.GetProperty("id").GetString()!,
        f.GetProperty("title").GetString()!,
        f.GetProperty("page").GetInt32(),
        f.GetProperty("target").GetString()!,
        new Regex(f.GetProperty("match").GetString()!)
    ))
    .ToList();
var byId = features.ToDictionary(f => f.Id);

var vectorFiles = Directory.GetFiles(vectorsDir, "aprs101-*.json").OrderBy(p => p, StringComparer.Ordinal).ToList();
var vectors = vectorFiles
    .SelectMany(path =>
        JsonDocument
            .Parse(File.ReadAllText(path))
            .RootElement.GetProperty("vectors")
            .EnumerateArray()
            .Select(v => new Vector(
                v.GetProperty("id").GetString()!,
                v.GetProperty("title").GetString()!,
                v.GetProperty("spec").GetProperty("page").GetInt32(),
                v.GetProperty("status").GetString()!,
                v.GetProperty("features").EnumerateArray().Select(f => f.GetString()!).ToList(),
                Path.GetFileNameWithoutExtension(path)
            ))
    )
    .ToList();

var corpusFiles = Directory
    .GetFiles(corpusDir, "*.log", SearchOption.AllDirectories)
    .OrderBy(p => p, StringComparer.Ordinal)
    .ToList();
var packets = corpusFiles
    .SelectMany(path => File.ReadAllLines(path, latin1))
    .Where(line => line.Length > 0)
    .Select(line => line.Length > 25 && line[24] == ' ' ? line[25..] : line)
    .Select(Packet.From)
    .Where(p => p is not null)
    .Select(p => p!)
    .ToList();

// Which packets match each feature (indexes into `packets`).
var matches = features.ToDictionary(
    f => f.Id,
    f => Enumerable.Range(0, packets.Count).Where(i => f.Match.IsMatch(packets[i].Target(f.Target))).ToHashSet()
);

Directory.CreateDirectory(outDir);
var chapterDocs = new List<(string File, string Title, int Total, int Seen)>();
foreach (var group in vectors.GroupBy(v => v.File))
{
    var name = group.Key.Replace("aprs101-", "", StringComparison.Ordinal);
    var chapter = int.Parse(name[2..4], inv);
    var title = $"Chapter {chapter}: {ChapterTitle(chapter)}";
    var doc = new StringBuilder();
    doc.Append(inv, $"# APRS101 {title} — vectors seen in real traffic\n\n");
    doc.Append(
        "Generated by `dotnet run tools/corpus/Coverage.cs`. Do not edit by hand. A vector is **seen** when one corpus "
            + "packet matches every feature it lists; the example is the first such packet (anonymized). "
            + "Control bytes are shown as `\\xNN`.\n\n"
    );
    doc.Append("| Vector | Spec | Status | Seen | Features |\n| --- | --- | --- | --- | --- |\n");

    var details = new StringBuilder();
    var seen = 0;
    foreach (var vector in group)
    {
        var hits = vector.Features.Select(f => matches[f]).Aggregate((a, b) => a.Intersect(b).ToHashSet());
        if (hits.Count > 0)
        {
            seen++;
        }

        var featureList = string.Join(", ", vector.Features.Select(f => $"`{f}` ({matches[f].Count.ToString(inv)})"));
        doc.Append(
            inv,
            $"| `{vector.Id}`<br>{Cell(vector.Title)} | p.{vector.Page} | {vector.Status} | "
                + $"{(hits.Count > 0 ? $"✅ {hits.Count}" : "—")} | {featureList} |\n"
        );

        if (hits.Count > 0)
        {
            details.Append(inv, $"### `{vector.Id}`\n\n{hits.Count} matching packet(s). First:\n\n```text\n");
            details.Append(Escape(packets[hits.Min()].Line)).Append("\n```\n\n");
        }
    }

    doc.Append(
        inv,
        $"\n**{seen} of {group.Count()} vectors seen.** Feature counts in brackets are packets matching that feature alone.\n"
    );
    if (details.Length > 0)
    {
        doc.Append("\n## Examples from the corpus\n\n").Append(details);
    }

    var file = $"{name}.md";
    File.WriteAllText(Path.Combine(outDir, file), doc.ToString().TrimEnd('\n') + "\n");
    chapterDocs.Add((file, title, group.Count(), seen));
}

var index = new StringBuilder();
index.Append("# APRS101 test-vector coverage in real traffic\n\n");
index.Append(
    "Generated by `dotnet run tools/corpus/Coverage.cs` from the vectors in "
        + "`tests/AprsNet.Packets.SpecTests/Vectors` and the anonymized captures in `tests/corpus`. Do not edit by hand.\n\n"
);
index.Append(
    inv,
    $"- Corpus: {packets.Count} packets ({packets.Select(p => p.Line).Distinct(StringComparer.Ordinal).Count()} distinct) from "
);
index.Append(string.Join(", ", corpusFiles.Select(f => $"`{f.Replace('\\', '/')}`"))).Append('\n');
index.Append(
    inv,
    $"- Vectors: {vectors.Count}, of which **{chapterDocs.Sum(c => c.Seen)}** have been seen in real traffic\n\n"
);
index.Append("| Chapter | Vectors | Seen |\n| --- | --- | --- |\n");
foreach (var (file, title, total, seenCount) in chapterDocs)
{
    index.Append(inv, $"| [{title}]({file}) | {total} | {seenCount} |\n");
}

index.Append("\n## Features\n\n");
index.Append(
    "Each vector lists the features it exercises. Counts are corpus packets matching the feature's pattern "
        + "(`tests/AprsNet.Packets.SpecTests/Vectors/features.json`). Features with no hits are formats we have never "
        + "received; their vectors rely on the spec alone.\n\n"
);
index.Append("| Feature | Description | Spec | Corpus packets |\n| --- | --- | --- | --- |\n");
foreach (var feature in features)
{
    var count = matches[feature.Id].Count;
    index.Append(
        inv,
        $"| `{feature.Id}` | {Cell(feature.Title)} | p.{feature.Page} | {(count > 0 ? count.ToString(inv) : "—")} |\n"
    );
}

var unused = features.Where(f => !vectors.Any(v => v.Features.Contains(f.Id))).Select(f => f.Id).ToList();
if (unused.Count > 0)
{
    index
        .Append("\nFeatures not used by any vector: ")
        .Append(string.Join(", ", unused.Select(u => $"`{u}`")))
        .Append('\n');
}

File.WriteAllText(Path.Combine(outDir, "README.md"), index.ToString());
Console.WriteLine(
    $"{vectors.Count} vectors, {chapterDocs.Sum(c => c.Seen)} seen in {packets.Count} corpus packets -> {outDir}/"
);
return 0;

static string ChapterTitle(int chapter) =>
    chapter switch
    {
        4 => "AX.25 Addresses",
        6 => "Time and Position Formats",
        7 => "Data Extensions",
        8 => "Position and DF Reports",
        9 => "Compressed Positions",
        10 => "Mic-E",
        11 => "Objects and Items",
        12 => "Weather Reports",
        13 => "Telemetry",
        14 => "Messages, Bulletins and Announcements",
        15 => "Capabilities, Queries and Responses",
        16 => "Status Reports",
        17 => "Third-Party Traffic",
        18 => "User-Defined Data",
        19 => "Other Packets",
        20 => "Symbols",
        _ => $"Chapter {chapter}",
    };

static string Cell(string text) =>
    text.Replace("|", "\\|", StringComparison.Ordinal).Replace("`", "\\`", StringComparison.Ordinal);

static string Escape(string line)
{
    var sb = new StringBuilder(line.Length);
    foreach (var c in line)
    {
        if (c < 0x20 || c >= 0x7f)
        {
            sb.Append(CultureInfo.InvariantCulture, $"\\x{(int)c:X2}");
        }
        else
        {
            sb.Append(c);
        }
    }

    return sb.ToString();
}

internal sealed record Feature(string Id, string Title, int Page, string Target, Regex Match);

internal sealed record Vector(string Id, string Title, int Page, string Status, List<string> Features, string File);

internal sealed record Packet(string Line, string Info, string Destination)
{
    public static Packet? From(string line)
    {
        var colon = line.IndexOf(':', StringComparison.Ordinal);
        var gt = line.IndexOf('>', StringComparison.Ordinal);
        if (colon < 0 || gt < 0 || gt > colon)
        {
            return null;
        }

        var destination = line[(gt + 1)..colon].Split(',')[0].Split('-')[0];
        return new Packet(line, line[(colon + 1)..], destination);
    }

    public string Target(string target) =>
        target switch
        {
            "info" => Info,
            "dest" => Destination,
            _ => Line,
        };
}
