// Writes the symbol pages from AprsNet.Symbols, so they always show what the library draws:
//
//   docs/symbols/<style>.md                 every symbol, overlay examples and unassigned codes (committed)
//   docs/symbols/<style>/*.svg              the images those pages show (committed)
//   artifacts/symbols/<style>/gallery.html  a review page with map sizes and map backgrounds (not committed)
//
//   dotnet run tools/symbols/Generate.cs -- [--docs docs/symbols] [--gallery artifacts/symbols]   (from the repository root)
//
// The symbols workflow runs this when the library or this tool changes, and fails a pull request whose pages are
// out of date.

using System.Globalization;
using System.Net;
using System.Text;
using AprsNet.Packets;
using AprsNet.Symbols;

var docsDir = "docs/symbols";
var galleryDir = "artifacts/symbols";
for (var i = 0; i < args.Length - 1; i++)
{
    switch (args[i])
    {
        case "--docs":
            docsDir = args[++i];
            break;
        case "--gallery":
            galleryDir = args[++i];
            break;
    }
}

// Overlays to show: overlay families with their defined meanings, then symbols that show an overlay as a corner badge.
var overlayDemos = new (string Key, string Overlays)[]
{
    ("\\#", "I1SWX"),
    ("\\&", "ILRTW2"),
    ("\\0", "EIAWV"),
    ("\\A", "RDAE9"),
    ("\\>", "BEHST"),
    ("\\n", "AB12"),
    ("\\^", "DJHV"),
    ("\\a", "ARSW"),
    ("\\c", "DRS"),
    ("\\s", "CFJS"),
    ("\\u", "BGPT"),
    ("\\z", "CGMT"),
    ("\\-", "ESWO"),
    ("\\h", "CEFH"),
    ("\\D", "ABFR"),
    ("\\%", "NSWH"),
};

var drawnInfos = AprsSymbolCatalog
    .All.Where(s => s.Status is AprsSymbolStatus.Assigned or AprsSymbolStatus.Legacy)
    .ToList();
var notDrawn = AprsSymbolCatalog
    .All.Where(s => s.Status is AprsSymbolStatus.Unassigned or AprsSymbolStatus.Reserved)
    .ToList();

foreach (var style in Enum.GetValues<AprsSymbolStyle>())
{
    var name = style.ToString().ToLowerInvariant();
    var imageDir = Path.Combine(docsDir, name);
    Directory.CreateDirectory(Path.Combine(imageDir, "overlays"));
    foreach (var stale in Directory.GetFiles(imageDir, "*.svg", SearchOption.AllDirectories))
    {
        File.Delete(stale);
    }

    var drawn = drawnInfos.Select(info => (info, AprsSymbolImages.GetSvg(info.Symbol, style))).ToList();
    foreach (var (info, svg) in drawn)
    {
        File.WriteAllText(Path.Combine(imageDir, Markdown.FileName(info.Symbol)), svg);
    }

    var unassigned = AprsSymbolImages.GetSvg(notDrawn[0].Symbol, style);
    File.WriteAllText(Path.Combine(imageDir, "unassigned.svg"), unassigned);

    var overlays = overlayDemos
        .Select(d =>
        {
            var info = AprsSymbolCatalog.Get(new AprsSymbol(d.Key[0], d.Key[1]));
            var variants = d
                .Overlays.Select(c =>
                {
                    var symbol = new AprsSymbol(c, info.Symbol.Code);
                    var svg = AprsSymbolImages.GetSvg(symbol, style);
                    File.WriteAllText(Path.Combine(imageDir, "overlays", Markdown.FileName(symbol)), svg);
                    return (c, svg, info.OverlayNames.GetValueOrDefault(c));
                })
                .ToList();
            return (info, variants);
        })
        .ToList();

    File.WriteAllText(Path.Combine(docsDir, $"{name}.md"), Markdown.Page(style, name, drawn, notDrawn, overlays));

    var galleryPath = Path.Combine(galleryDir, name, "gallery.html");
    Directory.CreateDirectory(Path.GetDirectoryName(galleryPath)!);
    File.WriteAllText(galleryPath, Gallery.Html(name, drawn, unassigned, overlays));
    Console.WriteLine($"{name}: {drawn.Count} symbols -> {docsDir}/{name}.md; gallery: {galleryPath}");
}

internal static class Markdown
{
    public static string Page(
        AprsSymbolStyle style,
        string name,
        List<(AprsSymbolInfo Info, string Svg)> drawn,
        List<AprsSymbolInfo> notDrawn,
        List<(AprsSymbolInfo Info, List<(char Overlay, string Svg, string? Meaning)> Variants)> overlays
    )
    {
        var other = style == AprsSymbolStyle.Modern ? "conventional" : "modern";
        var md = new StringBuilder();
        md.Append(
            CultureInfo.InvariantCulture,
            $"""
            <!-- Generated by tools/symbols/Generate.cs from src/AprsNet.Symbols. Do not edit: the symbols workflow regenerates this page. -->

            # {(style == AprsSymbolStyle.Modern ? "Modern" : "Conventional")} APRS symbols

            Every APRS symbol as drawn by the `AprsNet.Symbols` library in the {name} style:
            `AprsSymbolImages.GetSvg(symbol, AprsSymbolStyle.{style})`. See also the [{other} style]({other}.md).

            {(style == AprsSymbolStyle.Modern
                ? "Each symbol is a white glyph on a disc coloured by its category. Overlay families keep their shape (star, diamond, circle, box, triangle) as the coloured container."
                : "Shapes and colours long-time APRS users recognise, with dark outlines so they read on light and dark maps.")}
            Images are SVG on a 48×48 grid, shown here at 24 and 48 px. {drawn.Count} symbols are drawn: every assigned
            symbol and every legacy one older stations still send. Meanings come from APRS101 Appendix 2 and the APRS 1.1
            and 1.2 symbol lists.

            - [Primary table](#primary-table)
            - [Alternate table](#alternate-table)
            - [Overlays](#overlays)
            - [Unassigned and reserved codes](#unassigned-and-reserved-codes)

            """
        );

        foreach (var (title, table) in new[] { ("Primary table", '/'), ("Alternate table", '\\') })
        {
            md.Append(CultureInfo.InvariantCulture, $"\n## {title}\n\n");
            md.Append("| Symbol | 24 px | 48 px | Name | Category | Destination code |\n");
            md.Append("| --- | :-: | :-: | --- | --- | --- |\n");
            foreach (var (info, _) in drawn.Where(d => d.Info.Symbol.Table == table))
            {
                var path = $"{name}/{FileName(info.Symbol)}";
                var legacy = info.Status == AprsSymbolStatus.Legacy ? " *(legacy)*" : "";
                md.Append(
                    CultureInfo.InvariantCulture,
                    $"| {Code(info.Symbol.ToString())} | {Img(path, 24, info.Symbol)} | {Img(path, 48, info.Symbol)} | {Text(info.Name)}{legacy} | {info.Category} | {Code(info.DestinationCode)} |\n"
                );
            }
        }

        md.Append(
            """

            ## Overlays

            An alternate-table symbol can carry an overlay character, 0–9 or A–Z, sent in place of the table identifier.
            Symbols designed for overlays show the character in the shape; any other alternate symbol shows it as a corner
            badge. Meanings are from the APRS 1.2 overlay list.

            """
        );
        foreach (var (info, variants) in overlays)
        {
            md.Append(CultureInfo.InvariantCulture, $"\n### {Code(info.Symbol.ToString())} {Text(info.Name)}\n\n");
            md.Append("| Symbol | 48 px | Meaning |\n| --- | :-: | --- |\n");
            foreach (var (overlay, _, meaning) in variants)
            {
                var symbol = new AprsSymbol(overlay, info.Symbol.Code);
                md.Append(
                    CultureInfo.InvariantCulture,
                    $"| {Code(symbol.ToString())} | {Img($"{name}/overlays/{FileName(symbol)}", 48, symbol)} | {(meaning is null ? "*No defined meaning*" : Text(meaning))} |\n"
                );
            }
        }

        md.Append(
            CultureInfo.InvariantCulture,
            $"""

            ## Unassigned and reserved codes

            {Img($"{name}/unassigned.svg", 48, null)}

            These codes have no meaning, or are reserved, and share the international "not" sign (APRS 1.1):
            {string.Join(", ", notDrawn.Select(s => Code(s.Symbol.ToString())))}.

            """
        );
        return md.ToString();
    }

    /// <summary>p-3E.svg for /&gt;, a-3E.svg for \&gt;, E-30.svg for overlay E on \0: safe on every file system.</summary>
    public static string FileName(AprsSymbol symbol) =>
        $"{symbol.Table switch
        {
            '/' => "p",
            '\\' => "a",
            _ => symbol.Table.ToString(),
        }}-{(int)symbol.Code:X2}.svg";

    // A code span that survives any symbol character, including ` and |.
    private static string Code(string text) =>
        $"<code>{WebUtility.HtmlEncode(text).Replace("|", "&#124;", StringComparison.Ordinal).Replace("`", "&#96;", StringComparison.Ordinal).Replace("\\", "&#92;", StringComparison.Ordinal)}</code>";

    private static string Text(string text) =>
        WebUtility
            .HtmlEncode(text)
            .Replace("\\", "&#92;", StringComparison.Ordinal)
            .Replace("`", "&#96;", StringComparison.Ordinal)
            .Replace("|", "&#124;", StringComparison.Ordinal)
            .Replace("*", "&#42;", StringComparison.Ordinal)
            .Replace("_", "&#95;", StringComparison.Ordinal);

    private static string Img(string path, int size, AprsSymbol? symbol) =>
        $"<img src=\"{path}\" width=\"{size}\" height=\"{size}\" alt=\"{WebUtility.HtmlEncode(symbol?.ToString() ?? "unassigned")}\">";
}

internal static class Gallery
{
    public static string Html(
        string style,
        List<(AprsSymbolInfo Symbol, string Svg)> drawn,
        string unassigned,
        List<(AprsSymbolInfo Symbol, List<(char Overlay, string Svg, string? Meaning)> Variants)> overlays
    )
    {
        string Cards(char table) =>
            string.Concat(
                drawn
                    .Where(d => d.Symbol.Symbol.Table == table)
                    .OrderBy(d => d.Symbol.Symbol.Code)
                    .Select(d => Card(d.Symbol.Symbol.ToString(), d.Symbol.Name, d.Svg))
            );

        var rows = new StringBuilder();
        foreach (var (symbol, variants) in overlays)
        {
            rows.Append(
                CultureInfo.InvariantCulture,
                $"<section class=\"family\"><header><code>{E(symbol.Symbol.ToString())}</code><span>{E(symbol.Name)}</span></header><div class=\"variants\">"
            );
            foreach (var (overlay, svg, meaning) in variants)
            {
                rows.Append(
                    CultureInfo.InvariantCulture,
                    $"<figure><div class=\"tile map-light\">{Img(svg, 48)}</div><div class=\"tile map-dark\">{Img(svg, 48)}</div><figcaption><code>{E($"{overlay}{symbol.Symbol.Code}")}</code> {E(meaning ?? "no defined meaning")}</figcaption></figure>"
                );
            }

            rows.Append("</div></section>");
        }

        return Template
            .Replace(
                "{{TITLE}}",
                style == "modern" ? "APRS Modern Symbol Proofs" : "APRS Symbol Proofs",
                StringComparison.Ordinal
            )
            .Replace("{{STYLE}}", style, StringComparison.Ordinal)
            .Replace("{{COUNT}}", drawn.Count.ToString(CultureInfo.InvariantCulture), StringComparison.Ordinal)
            .Replace("{{PRIMARY}}", Cards('/'), StringComparison.Ordinal)
            .Replace("{{ALTERNATE}}", Cards('\\'), StringComparison.Ordinal)
            .Replace("{{UNASSIGNED}}", Card("—", "Unassigned and reserved codes", unassigned), StringComparison.Ordinal)
            .Replace("{{OVERLAYS}}", rows.ToString(), StringComparison.Ordinal);
    }

    private static string Card(string key, string name, string svg) =>
        $"""
            <article class="card">
              <header><code>{E(key)}</code><span>{E(name)}</span></header>
              <div class="sizes map-light">{Img(svg, 16)}{Img(svg, 24)}{Img(svg, 32)}{Img(svg, 48)}</div>
              <div class="large">{Img(svg, 112)}</div>
              <div class="grounds"><div class="tile map-dark">{Img(svg, 24)}</div><div class="tile map-terrain">{Img(
                svg,
                24
            )}</div><div class="tile map-sea">{Img(svg, 24)}</div></div>
            </article>
            """;

    private static string Img(string svg, int size) =>
        $"<img src=\"data:image/svg+xml;base64,{Convert.ToBase64String(Encoding.UTF8.GetBytes(svg))}\" width=\"{size}\" height=\"{size}\" alt=\"\">";

    private static string E(string text) => System.Net.WebUtility.HtmlEncode(text);

